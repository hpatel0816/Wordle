// Writes the migration that loads Word-Bank.txt into the words table, using
// the same answer pool rules as the app (getAnswerPool).
// Run with: npm run db:words
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getAnswerPool, parseWordList } from "../src/gameLogic.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const words = parseWordList(fs.readFileSync(path.join(root, "src/Word-Bank.txt"), "utf8"));
const answers = new Set(getAnswerPool(words));

const rows = words.map((word) => `('${word}', ${answers.has(word)})`);
const sql = `-- Generated by scripts/generate-words-migration.mjs from src/Word-Bank.txt.
-- Do not edit by hand. ${words.length} words, ${answers.size} possible answers.
insert into public.words (word, is_answer) values
${rows.join(",\n")}
on conflict (word) do update set is_answer = excluded.is_answer;
`;

const out = path.join(root, "supabase/migrations/20261111000100_load_words.sql");
fs.writeFileSync(out, sql);
console.log(`Wrote ${words.length} words (${answers.size} answers) to ${path.relative(root, out)}`);
